export function translate(
  key: TranslationKey,
  language: string,
  variables: TranslationVariables = {}
): string {
  const catalog = language.toLowerCase().startsWith("zh") ? ZH : EN;
  return catalog[key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : placeholder);
}
